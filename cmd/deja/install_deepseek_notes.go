package main

import (
	"os"
	"path/filepath"
	"strings"

	dejavu "github.com/vshulcz/deja-vu"
	"github.com/vshulcz/deja-vu/internal/sources"
)

// deja's lines for the person — the "you have been here" receipt, the build
// and week notes — reach the model only, unless something draws them. The npm
// plugin draws them as a card above dsh web's input (#4984); a profile wired by
// `deja install dsh-auto` gets the same card from the same files (#4983).
//
// auto.js keeps the lines on a board and answers /api/deja-notes, the way the
// npm plugin's index.js does, with lib.js written beside it. The card is the
// npm plugin's client.js. dsh serves a browser half only for a package whose
// package.json declares dsh.client, found from a profile row's module, and two
// rows resolving to one package are refused, so the card ships as a package of
// its own with a row whose host half does nothing.

const dshNotesPackage = "deja-notes"

func dshNotesDir() string {
	return filepath.Join(sources.DSHHome(), "plugins", dshNotesPackage)
}

func dshNotesPath() string { return filepath.Join(dshNotesDir(), "index.js") }

func dshLibPath() string { return filepath.Join(filepath.Dir(dshAutoPath()), "lib.js") }

func dshNotesRow(withAuto bool) string {
	if !withAuto || !dshPackageIsOurs(dshNotesDir()) {
		return ""
	}
	return "    - id: deja-notes\n" +
		"      name: " + yamlQuote(dshNotesPath()) + "\n"
}

// The version is required: dsh 0.2's plugin inventory refuses a package without
// one, and that refusal fails every model request.
const dshNotesPackageJSON = `{
  "name": "deja-notes",
  "version": "1.0.0",
  "type": "module",
  "exports": {
    ".": "./index.js",
    "./client": "./client.js"
  },
  "dsh": {
    "client": {
      "platform": "web"
    }
  }
}
`

const dshNotesServerJS = `// generated by deja install; cordis.patch.yml loads this file — remove with: deja install deepseek
// The browser half (client.js) is why this row exists. The lines it draws come
// from auto.js, which runs the hooks and answers /api/deja-notes. This half
// only says the row is loaded: with it switched off there is no card, and
// auto.js keeps asking deja for --plain rather than spend notes nobody sees.
const LOADED = Symbol.for("deja-vu.dsh.notes-card");

export default function apply(ctx) {
  const mark = () => {
    globalThis[LOADED] = (globalThis[LOADED] || 0) + 1;
    return () => {
      globalThis[LOADED] -= 1;
    };
  };
  if (ctx && typeof ctx.effect === "function") ctx.effect(mark, "deja-notes: loaded");
  else mark();
}
`

// dshNotesClientJS is the npm plugin's card. A browser bundle registers under
// its package's name, so the id is the only line that changes.
func dshNotesClientJS() string {
	return "// generated by deja install from extensions/dsh/client.js\n" +
		strings.Replace(dejavu.DSHClientJS, `id: "dsh-deja",`, `id: "`+dshNotesPackage+`",`, 1)
}

func dshLibJS() string {
	return "// generated by deja install from extensions/dsh/lib.js\n" + dejavu.DSHLibJS
}

// writeDSHNotes writes lib.js beside auto.js and, unless someone else's
// package holds the name, the card's package, and returns what happened to
// them as one action.
func writeDSHNotes() (string, error) {
	files := []struct{ path, body string }{{dshLibPath(), dshLibJS()}}
	dir := dshNotesDir()
	if dshPackageIsOurs(dir) {
		noteCreatedDirs(dir)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return "", err
		}
		files = append(files, []struct{ path, body string }{
			{filepath.Join(dir, "package.json"), dshNotesPackageJSON},
			{dshNotesPath(), dshNotesServerJS},
			{filepath.Join(dir, "client.js"), dshNotesClientJS()},
		}...)
	}
	action := "unchanged"
	for _, f := range files {
		old, err := readConfig(f.path)
		if err != nil {
			return "", err
		}
		a, err := writeIfChanged(f.path, old, []byte(f.body))
		if err != nil {
			return "", err
		}
		if a != "unchanged" && action == "unchanged" {
			action = a
		}
	}
	return action, nil
}

// removeDSHNotes takes back what writeDSHNotes wrote.
func removeDSHNotes() error {
	if err := os.Remove(dshLibPath()); err != nil && !os.IsNotExist(err) {
		return err
	}
	return removeDSHPackage(dshNotesDir())
}

// dshPackageIsOurs reports whether deja may write or remove a plugin package
// directory: it is not there, or its index.js is the one deja generates. A
// plugins/deja-notes or plugins/deja-status somebody wrote is theirs, and was
// overwritten on install and deleted on uninstall.
func dshPackageIsOurs(dir string) bool {
	b, err := os.ReadFile(filepath.Join(dir, "index.js"))
	if err == nil {
		return strings.HasPrefix(string(b), "// generated by deja install")
	}
	if !os.IsNotExist(err) {
		return false
	}
	// No index.js: only an empty directory, or one with nothing but deja's
	// other file names in it, is a half-written package of deja's.
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return true
	}
	if err != nil {
		return false
	}
	for _, e := range entries {
		if e.Name() != "package.json" && e.Name() != "client.js" {
			return false
		}
	}
	pkg, err := os.ReadFile(filepath.Join(dir, "package.json"))
	return err != nil || strings.Contains(string(pkg), `"name": "`+filepath.Base(dir)+`"`)
}

func removeDSHPackage(dir string) error {
	if !dshPackageIsOurs(dir) {
		return nil
	}
	return os.RemoveAll(dir)
}

func dshForeignNote(dirs []string) string {
	names := make([]string, len(dirs))
	for i, d := range dirs {
		names[i] = reportPath(d)
	}
	return "left " + strings.Join(names, " and ") + " alone: not written by deja, so dsh loads no deja row for it"
}
