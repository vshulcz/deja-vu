// Command genlogo draws the SVG assets from the same sprite the terminal banner
// prints, so the mark on a page and the mark in a terminal cannot drift.
//
// They were hand-authored before this existed, which meant editing the sprite
// left the assets behind silently. Run it after any change to internal/mark:
//
//	go run ./scripts/genlogo
//
// The favicon is deliberately not generated. It is not this sprite scaled down —
// the whole animal at 16px is mush, so it was redrawn as the head alone on a
// 16-unit grid where one cell lands on exactly one device pixel.
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/vshulcz/deja-vu/internal/mark"
)

const note = `  <!-- Generated by scripts/genlogo from internal/mark. Do not hand-edit: the
     sprite is the source, and the terminal banner draws from the same grid.
     Coat, accent and features are the three colours xterm-256 holds exactly,
     so vector and terminal agree. -->
`

func fills(paths []mark.Path, indent int) string {
	pad := strings.Repeat(" ", indent)
	var b strings.Builder
	for _, p := range paths {
		fmt.Fprintf(&b, "%s<path fill=\"%s\" d=\"%s\"/>\n", pad, p.Fill, p.D)
	}
	return b.String()
}

// movingTail is every cell any wag position touches. The tail hangs clear of the
// body, so those cells are left out of the still layer entirely and each wag
// position draws its own.
//
// The eyes are not handled this way. They sit on the head, and cutting them out
// would leave two holes whenever the blink hides the open pair — the still layer
// carries coat there instead, and the eye groups paint over it.
func movingTail() map[mark.Cell]bool {
	out := map[mark.Cell]bool{}
	for _, pose := range mark.WagCycle {
		for _, c := range mark.Tails[pose] {
			out[c] = true
		}
	}
	// The ears too. Every cell either pose paints comes out of the still layer,
	// so each pose can be drawn as its own group. Filling the dropped ones with
	// the background colour instead worked on the dark icon and put a black
	// notch on the light logo, where the background is neither dark nor there.
	for c := range earCells(mark.Ears["up"]) {
		out[c] = true
	}
	for c := range earCells(mark.Ears["flick"]) {
		out[c] = true
	}
	return out
}

// alive writes the tail and the eyes as animated groups.
//
// The tail is three positions of the same cells, ping-ponged: the tip travels
// out and comes back. Two positions alternating is a twitch, not a gesture. The
// blink is the eye rows swapping, shut for about a tenth of a cycle, which is
// roughly how long a cat's blink is.
//
// The timings match the ones deja stats already uses, so the two pages animate
// the same animal at the same rate rather than at two guesses.
func alive(x0, y0, size int) string {
	breath := size / 6
	if breath < 1 {
		breath = 1
	}
	glance := size / 2
	if glance < 1 {
		glance = 1
	}
	var b strings.Builder
	seen := map[string]bool{}
	poses := []string{}
	for _, p := range mark.WagCycle {
		if !seen[p] {
			seen[p] = true
			poses = append(poses, p)
		}
	}
	for i, pose := range poses {
		fmt.Fprintf(&b, "  <g class=\"t%d\"><path fill=\"%s\" d=\"%s\"/></g>\n",
			i, mark.Hex[mark.Coat], mark.CellsD(mark.Tails[pose], x0, y0, size))
	}
	// Every eye state as its own group, all of them inside one that can move.
	// The blink passes through the half-lid rather than cutting from open to
	// shut, which is what an eyelid does; the glance slides the whole group
	// sideways, which is what an eye does.
	b.WriteString("  <g class=\"eyes\">\n")
	for _, eye := range []struct{ class, set string }{
		{"eyes-open", "tall"}, {"eyes-low", "low"}, {"eyes-shut", "closed"},
	} {
		fmt.Fprintf(&b, "    <g class=\"%s\"><path fill=\"%s\" d=\"%s\"/></g>\n",
			eye.class, mark.Hex[mark.Feature],
			mark.CellsD(mark.Eyes[eye.set], x0, y0, size))
	}
	b.WriteString("  </g>\n")

	// Both ear poses, each as its own group, swapped by the flick.
	for _, ear := range []struct {
		class, pose string
	}{{"ear-up", "up"}, {"ear-flick", "flick"}} {
		fmt.Fprintf(&b, "  <g class=\"%s\"><path fill=\"%s\" d=\"%s\"/></g>\n",
			ear.class, mark.Hex[mark.Coat],
			mark.CellsD(sortCells(cellList(earCells(mark.Ears[ear.pose]))), x0, y0, size))
	}

	css := `  <style>
    .t1, .t2, .eyes-low, .eyes-shut, .ear-flick { opacity: 0 }
    @media (prefers-reduced-motion: no-preference) {
      /* The one continuous motion on the mark. Everything else cuts between
         poses; this eases, and a creature that is never perfectly still is the
         difference between an animal and a diagram. */
      .breathe { animation: dv-breathe 4.3s cubic-bezier(.45,0,.55,1) infinite }
      .t0  { animation: dv-t0 4.7s steps(1, end) infinite }
      .t1  { animation: dv-t1 4.7s steps(1, end) infinite }
      .t2  { animation: dv-t2 4.7s steps(1, end) infinite }
      .eyes-open { animation: dv-open 7.3s steps(1, end) infinite }
      .eyes-low  { animation: dv-low 7.3s steps(1, end) infinite }
      .eyes-shut { animation: dv-shut 7.3s steps(1, end) infinite }
      .eyes { animation: dv-glance 9.7s cubic-bezier(.4,0,.5,1) infinite }
      .ear-up    { animation: dv-ear-up 11.3s steps(1, end) infinite }
      .ear-flick { animation: dv-ear 11.3s steps(1, end) infinite }
    }
    @keyframes dv-breathe { 0%, 100% { transform: translateY(0) } 50% { transform: translateY(SIZEpx) } }
    /* The tail rests for four fifths of its cycle, then sweeps out and back. */
    @keyframes dv-t0 { 0%, 79.9% { opacity: 1 } 80%, 96.9% { opacity: 0 } 97%, 100% { opacity: 1 } }
    @keyframes dv-t1 { 0%, 79.9% { opacity: 0 } 80%, 84.9% { opacity: 1 } 85%, 91.9% { opacity: 0 } 92%, 96.9% { opacity: 1 } 97%, 100% { opacity: 0 } }
    @keyframes dv-t2 { 0%, 84.9% { opacity: 0 } 85%, 91.9% { opacity: 1 } 92%, 100% { opacity: 0 } }
    /* A blink through the half-lid and back, then a slower one a beat later. */
    @keyframes dv-open { 0%, 87.4% { opacity: 1 } 87.5%, 91.4% { opacity: 0 } 91.5%, 95.4% { opacity: 1 } 95.5%, 99.4% { opacity: 0 } 99.5%, 100% { opacity: 1 } }
    @keyframes dv-low  { 0%, 87.4% { opacity: 0 } 87.5%, 88.4% { opacity: 1 } 88.5%, 90.4% { opacity: 0 } 90.5%, 91.4% { opacity: 1 } 91.5%, 95.4% { opacity: 0 } 95.5%, 96.9% { opacity: 1 } 97%, 98.4% { opacity: 0 } 98.5%, 99.4% { opacity: 1 } 99.5%, 100% { opacity: 0 } }
    @keyframes dv-shut { 0%, 88.4% { opacity: 0 } 88.5%, 90.4% { opacity: 1 } 90.5%, 96.9% { opacity: 0 } 97%, 98.4% { opacity: 1 } 98.5%, 100% { opacity: 0 } }
    /* Looks aside, holds it a moment, looks back. */
    @keyframes dv-glance { 0%, 70% { transform: translateX(0) } 74%, 84% { transform: translateX(GLANCEpx) } 88%, 100% { transform: translateX(0) } }
    @keyframes dv-ear { 0%, 96.9% { opacity: 0 } 97%, 99.4% { opacity: 1 } 99.5%, 100% { opacity: 0 } }
    @keyframes dv-ear-up { 0%, 96.9% { opacity: 1 } 97%, 99.4% { opacity: 0 } 99.5%, 100% { opacity: 1 } }
  </style>
`
	css = strings.ReplaceAll(css, "SIZEpx", fmt.Sprintf("%dpx", breath))
	css = strings.ReplaceAll(css, "GLANCEpx", fmt.Sprintf("%dpx", glance))
	b.WriteString(css)
	return b.String()
}

// earCells turns an ear pose's rows into the set of cells it paints.
func earCells(rows []string) map[mark.Cell]bool {
	out := map[mark.Cell]bool{}
	src := rows
	if src == nil {
		src = mark.Body[:4]
	}
	for r, row := range src {
		for c, ch := range row {
			if ch == '#' {
				out[mark.Cell{Row: r, Col: c}] = true
			}
		}
	}
	return out
}

func cellList(set map[mark.Cell]bool) []mark.Cell {
	out := make([]mark.Cell, 0, len(set))
	for c := range set {
		out = append(out, c)
	}
	return out
}

func sortCells(in []mark.Cell) []mark.Cell {
	sort.Slice(in, func(i, j int) bool {
		if in[i].Row != in[j].Row {
			return in[i].Row < in[j].Row
		}
		return in[i].Col < in[j].Col
	})
	return in
}

func logo(ink string, animate bool) string {
	const x0, y0, size = 36, 19, 6
	still := mark.Ready
	var skip func(mark.Cell) bool
	var parts string
	if animate {
		tail := movingTail()
		skip = func(c mark.Cell) bool { return tail[c] }
		still.EyeSet = "none"
		parts = alive(x0, y0, size)
	}
	// The whole animal breathes, so the group wraps the still body and every
	// moving part alike — a breath that moved only the body would tear the cat
	// away from its own tail.
	cat := fills(mark.Paths(still, x0, y0, size, skip), 2) + parts
	if animate {
		cat = "  <g class=\"breathe\">\n" + cat + "  </g>\n"
	}
	return `<svg xmlns="http://www.w3.org/2000/svg" width="620" height="170" viewBox="0 0 620 170" role="img" aria-label="deja-vu">
` + note + cat +
		`  <g font-family="SF Mono, JetBrains Mono, Fira Code, Menlo, monospace">
    <text x="208" y="105" font-size="72" font-weight="700" fill="` + ink + `">deja-vu</text>
  </g>
</svg>
`
}

// The icon does not move. It is used as an avatar and an app icon, sizes where a
// travelling two-pixel tip is a flicker rather than a gesture.
func icon() string {
	const x0, y0, size = 56, 68, 12
	return `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400" role="img" aria-label="deja-vu">
  <rect width="400" height="400" rx="88" fill="#1d1b2e"/>
` + note + fills(mark.Paths(mark.Ready, x0, y0, size, nil), 2) + "</svg>\n"
}

// liveIcon is the app icon with the cat alive in it: the same wag and blink the
// wordmark carries. The site needs a file rather than inline markup, because an
// SVG referenced by <img> still runs its own CSS animations — which is how the
// header mark moves without the page owning a second copy of the sprite.
func liveIcon() string {
	const x0, y0, size = 56, 68, 12
	tail := movingTail()
	still := mark.Ready
	still.EyeSet = "none"
	return `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400" role="img" aria-label="deja-vu">
  <rect width="400" height="400" rx="88" fill="#1d1b2e"/>
` + note + "  <g class=\"breathe\">\n" +
		fills(mark.Paths(still, x0, y0, size, func(c mark.Cell) bool { return tail[c] }), 2) +
		alive(x0, y0, size) + "  </g>\n</svg>\n"
}

// stillIcon is the app icon in a named mood, for the moments the site wants the
// cat to react: asleep while the tab is in the background, surprised when the
// demo search lands a hit. The page swaps the file rather than reaching into
// the drawing, which keeps the sprite in one place.
func stillIcon(m mark.Mood) string {
	const x0, y0, size = 56, 68, 12
	return `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="400" viewBox="0 0 400 400" role="img" aria-label="deja-vu">
  <rect width="400" height="400" rx="88" fill="#1d1b2e"/>
` + note + fills(mark.Paths(m, x0, y0, size, nil), 2) + "</svg>\n"
}

func main() {
	check := flag.Bool("check", false, "fail if the committed assets differ from the sprite")
	static := flag.Bool("static", false, "draw the ready pose without the wag")
	flag.Parse()

	darkLogo := logo("#e8e6f0", !*static)
	appIcon := icon()
	assets := map[string]string{
		"assets/logo.svg":      logo("#1d1b2e", !*static),
		"assets/logo-dark.svg": darkLogo,
		"assets/icon.svg":      appIcon,
		// The site serves docs/ as its root, so it cannot reach the files
		// above. Written from the same sprite in the same run rather than
		// copied, because a copy is what goes stale — this is the drift the
		// whole command exists to stop.
		"docs/assets/logo-dark.svg":  darkLogo,
		"docs/assets/icon.svg":       appIcon,
		"docs/assets/icon-live.svg":  liveIcon(),
		"docs/assets/icon-sleep.svg": stillIcon(mark.Asleep),
		"docs/assets/icon-wow.svg":   stillIcon(mark.Surprised),
	}
	paths := make([]string, 0, len(assets))
	for p := range assets {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	// -check is what keeps the assets honest. Editing the sprite and forgetting
	// to regenerate is silent otherwise: the banner changes, the logo does not,
	// and nothing says which one is the product.
	stale := false
	for _, p := range paths {
		if *check {
			have, err := os.ReadFile(p)
			if err != nil {
				fmt.Fprintln(os.Stderr, err)
				os.Exit(1)
			}
			if string(have) != assets[p] {
				fmt.Fprintf(os.Stderr, "%s is stale: run go run ./scripts/genlogo\n", p)
				stale = true
			}
			continue
		}
		if err := os.WriteFile(p, []byte(assets[p]), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("wrote", p)
	}
	if stale {
		os.Exit(1)
	}
}
